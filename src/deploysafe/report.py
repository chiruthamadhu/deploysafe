from datetime import datetime, timezone
from pathlib import Path


def generate_report(findings, output_file="reports/deploysafe-report.md"):
    output = Path(output_file)
    output.parent.mkdir(parents=True, exist_ok=True)

    counts = {
        "CRITICAL": 0,
        "HIGH": 0,
        "MEDIUM": 0,
        "LOW": 0,
    }

    for finding in findings:
        severity = finding.get("severity", "LOW").upper()
        counts[severity] = counts.get(severity, 0) + 1

    if counts["CRITICAL"] > 0:
        status = "BLOCKED - Critical risks detected"
    elif counts["HIGH"] > 0:
        status = "REVIEW REQUIRED - High risks detected"
    elif counts["MEDIUM"] > 0:
        status = "REVIEW RECOMMENDED - Medium risks detected"
    else:
        status = "PASSED - No high-priority risks detected"

    lines = [
        "# DeploySafe Terraform Risk Report",
        "",
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        "",
        f"**Status:** {status}",
        "",
        "## Summary",
        "",
        f"- Total findings: **{len(findings)}**",
        f"- Critical: **{counts['CRITICAL']}**",
        f"- High: **{counts['HIGH']}**",
        f"- Medium: **{counts['MEDIUM']}**",
        f"- Low: **{counts['LOW']}**",
        "",
        "## Findings",
        "",
    ]

    if not findings:
        lines.append("No findings detected by the currently implemented rules.")
    else:
        recommendations = {
            "RESOURCE_DELETION": (
                "Review the Terraform plan and confirm the resource is safe to delete."
            ),
            "PUBLIC_S3_ACL": (
                "Remove public ACL access and review S3 Block Public Access settings."
            ),
            "ENCRYPTION_REMOVED": (
                "Restore the intended server-side encryption configuration."
            ),
        }

        for index, finding in enumerate(findings, start=1):
            rule = finding.get("rule", "UNKNOWN")
            recommendation = recommendations.get(
                rule,
                "Review this finding and apply the appropriate security control."
            )

            lines.extend([
                f"### {index}. {finding.get('severity', 'UNKNOWN')} — {rule}",
                "",
                f"- **Resource:** `{finding.get('resource', 'unknown')}`",
                f"- **Details:** {finding.get('message', 'No details provided')}",
                f"- **Recommendation:** {recommendation}",
                "",
            ])

    lines.extend([
        "---",
        "",
        "*Generated by DeploySafe. This report covers only the rules currently implemented.*",
        "",
    ])

    output.write_text("\n".join(lines), encoding="utf-8")
    return output


if __name__ == "__main__":
    import json
    import sys

    if len(sys.argv) != 2:
        print(
            f"Usage: {sys.argv[0]} <findings.json>",
            file=sys.stderr,
        )
        sys.exit(2)

    try:
        with open(sys.argv[1], encoding="utf-8") as file:
            findings = json.load(file)
    except (OSError, json.JSONDecodeError) as error:
        print(f"Could not read findings JSON: {error}", file=sys.stderr)
        sys.exit(2)

    if isinstance(findings, dict):
        findings = findings.get("findings")
    if not isinstance(findings, list):
        print("Input must be a findings list or analyzer JSON object.", file=sys.stderr)
        sys.exit(2)

    print(generate_report(findings))
